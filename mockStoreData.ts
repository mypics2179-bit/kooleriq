export function slot(
  doorPrefix: string,
  s: number,
  f: number,
  skuId: string,
  currentDepth: number,
  maxDepth = 6,
  options?: {
    plannedSkuId?: string;
    status?: FacingSlot['status'];
    aiRecommendation?: FacingSlot['aiRecommendation'];
  }
): FacingSlot {
  const coord = `S${s + 1}-F${String(f + 1).padStart(2, '0')}`;
  const plannedSkuId = options?.plannedSkuId ?? skuId;
  let status: FacingSlot['status'] = options?.status ?? 'optimal';
  if (!options?.status) {
    if (currentDepth === 0) status = 'oos';
    else if (skuId !== plannedSkuId) status = 'violation';
    else if (currentDepth / maxDepth <= 0.25) status = 'low';
  }
  return {
    id: `${doorPrefix}-${coord}`,
    coord,
    shelfIndex: s,
    facingIndex: f,
    skuId,
    plannedSkuId,
    currentDepth,
    maxDepth,
    status,
    aiRecommendation: options?.aiRecommendation,
  };
}

export function buildCustomDoor(params: {
  id: string;
  number: string;
  label: string;
  category: string;
  hardwareType: DoorHardwareType;
  shelvesCount: number;
  facingsPerShelf: number;
  defaultMaxDepth: number;
  skuPool: string[];
  tempF?: number;
}): CoolerDoor {
  const {
    id,
    number,
    label,
    category,
    hardwareType,
    shelvesCount,
    facingsPerShelf,
    defaultMaxDepth,
    skuPool,
    tempF = 34.4,
  } = params;
  const pool = skuPool.length > 0 ? skuPool : ['sku-coke-orig', 'sku-celsius-peach'];
  const prefix = `D${number}-${id.slice(-3)}`;

  const shelves: FacingSlot[][] = Array.from({ length: shelvesCount }).map((_, sIdx) =>
    Array.from({ length: facingsPerShelf }).map((__, fIdx) => {
      const skuId = pool[(sIdx * facingsPerShelf + fIdx) % pool.length];
      // Seed realistic depth variation without locking everything full
      const seed = (sIdx * 7 + fIdx * 3) % 9;
      const depth = seed === 0 ? 0 : seed === 1 ? 1 : defaultMaxDepth - (seed % 2);
      return slot(prefix, sIdx, fIdx, skuId, Math.max(0, Math.min(defaultMaxDepth, depth)), defaultMaxDepth);
    })
  );

  return {
    id,
    number,
    label,
    category,
    hardwareType,
    facingsPerShelf,
    defaultMaxDepth,
    tempF,
    targetTempF: 34.5,
    humidityPct: 42,
    doorOpensToday: 90 + shelvesCount * 14,
    lastAuditAt: 'Just configured',
    compressorState: 'nominal',
    shelves,
  };
}

